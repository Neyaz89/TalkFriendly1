"use client";

import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { 
  PROVIDER_INFO, 
  formatMeetingUrl, 
  getMeetingInstructions,
  isGeneratedJitsiUrl,
  type MeetingProvider 
} from "@/lib/meeting-url-utils";
import { Video, ExternalLink, Clock, Copy, Check } from "lucide-react";
import { useState } from "react";
import { useToast } from "@/hooks/useToast";

interface MeetingUrlDisplayProps {
  meetingUrl: string;
  provider?: MeetingProvider;
  appointmentTime?: Date;
  showJoinButton?: boolean;
  compact?: boolean;
}

export function MeetingUrlDisplay({ 
  meetingUrl, 
  provider = 'other',
  appointmentTime,
  showJoinButton = true,
  compact = false
}: MeetingUrlDisplayProps) {
  const [copied, setCopied] = useState(false);
  const { success } = useToast();

  const providerInfo = PROVIDER_INFO[provider];
  const isAutoGenerated = isGeneratedJitsiUrl(meetingUrl);

  const handleCopyUrl = async () => {
    try {
      await navigator.clipboard.writeText(meetingUrl);
      setCopied(true);
      success('Meeting link copied to clipboard');
      setTimeout(() => setCopied(false), 2000);
    } catch (error) {
      console.error('Failed to copy:', error);
    }
  };

  const handleJoinMeeting = () => {
    window.open(meetingUrl, '_blank', 'noopener,noreferrer');
  };

  // Check if meeting is happening soon (within 15 minutes)
  const isStartingSoon = appointmentTime 
    ? Math.abs(new Date(appointmentTime).getTime() - Date.now()) < 15 * 60 * 1000
    : false;

  if (compact) {
    return (
      <div className="flex items-center gap-2">
        <span className="text-sm text-gray-600 dark:text-gray-400">
          {providerInfo.icon} {providerInfo.name}
        </span>
        <Button 
          size="sm" 
          onClick={handleJoinMeeting}
          className="flex items-center gap-1"
        >
          <ExternalLink className="h-3 w-3" />
          Join
        </Button>
      </div>
    );
  }

  return (
    <Card className="p-6">
      <div className="space-y-4">
        {/* Header */}
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="p-2 bg-primary-100 dark:bg-primary-900/20 rounded-lg">
              <Video className="h-5 w-5 text-primary-600 dark:text-primary-400" />
            </div>
            <div>
              <h3 className="font-semibold">Video Meeting</h3>
              <div className="flex items-center gap-2 mt-1">
                <span className="text-xl">{providerInfo.icon}</span>
                <span className="text-sm text-gray-600 dark:text-gray-400">
                  {providerInfo.name}
                </span>
                {isAutoGenerated && (
                  <Badge variant="secondary" className="text-xs">
                    Auto-generated
                  </Badge>
                )}
              </div>
            </div>
          </div>

          {isStartingSoon && (
            <Badge variant="warning" className="flex items-center gap-1">
              <Clock className="h-3 w-3" />
              Starting Soon
            </Badge>
          )}
        </div>

        {/* Meeting URL */}
        <div className="p-3 bg-gray-50 dark:bg-gray-800 rounded-lg">
          <div className="flex items-center justify-between gap-2">
            <code className="text-sm text-gray-700 dark:text-gray-300 break-all">
              {formatMeetingUrl(meetingUrl, 60)}
            </code>
            <Button
              variant="ghost"
              size="sm"
              onClick={handleCopyUrl}
              className="shrink-0"
            >
              {copied ? (
                <Check className="h-4 w-4 text-green-600" />
              ) : (
                <Copy className="h-4 w-4" />
              )}
            </Button>
          </div>
        </div>

        {/* Instructions */}
        <p className="text-sm text-gray-600 dark:text-gray-400">
          {getMeetingInstructions(provider)}
        </p>

        {/* Join Button */}
        {showJoinButton && (
          <Button 
            onClick={handleJoinMeeting}
            className="w-full"
            size="lg"
          >
            <ExternalLink className="h-5 w-5 mr-2" />
            Join Meeting
          </Button>
        )}

        {/* Appointment Time */}
        {appointmentTime && (
          <div className="flex items-center gap-2 text-sm text-gray-600 dark:text-gray-400 pt-2 border-t">
            <Clock className="h-4 w-4" />
            <span>
              Scheduled: {new Date(appointmentTime).toLocaleString('en-US', {
                weekday: 'long',
                year: 'numeric',
                month: 'long',
                day: 'numeric',
                hour: '2-digit',
                minute: '2-digit'
              })}
            </span>
          </div>
        )}
      </div>
    </Card>
  );
}
